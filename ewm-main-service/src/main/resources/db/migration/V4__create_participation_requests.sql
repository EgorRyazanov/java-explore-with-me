CREATE TABLE participation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    requester_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELED')),
    CONSTRAINT uq_request_event_requester UNIQUE (event_id, requester_id)
);

CREATE INDEX idx_requests_event_status ON participation_requests (event_id, status, id);
CREATE INDEX idx_requests_requester ON participation_requests (requester_id, id);
